/**
 * Generate CSS variables from theme.js
 * Converts the theme object into CSS custom properties for use in stylesheets
 */

const fs = require('fs');
const path = require('path');

// Dynamically import theme.js
const theme = require('../src/css/theme.js').default;

// Convert camelCase or UPPER_CASE to kebab-case
function toKebabCase(str) {
  return str
    // Handle UPPER_CASE (e.g., PRIMARY_LIGHT -> primary-light)
    .replace(/_/g, '-')
    // Handle camelCase (e.g., borderRadius -> border-radius)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

// Recursively convert theme object to CSS variables
function generateCssVars(obj, prefix = '') {
  const vars = [];

  for (const [key, value] of Object.entries(obj)) {
    let kebabKey = toKebabCase(key);

    // Special handling for top-level plurals: colors -> color, sizes -> size
    if (!prefix && kebabKey === 'colors') {
      kebabKey = 'color';
    } else if (!prefix && kebabKey === 'sizes') {
      kebabKey = 'size';
    }

    const varName = prefix ? `${prefix}-${kebabKey}` : kebabKey;

    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      // Recursively handle nested objects
      vars.push(...generateCssVars(value, varName));
    } else {
      // Create CSS variable declaration
      vars.push(`  --${varName}: ${value};`);
    }
  }

  return vars;
}

// Generate the CSS file
function main() {
  console.log('Starting CSS variable generation...');
  console.log('Theme object:', theme);

  const cssVars = generateCssVars(theme);

  const cssContent = `/**
 * CSS Variables generated from theme.js
 * DO NOT EDIT THIS FILE DIRECTLY
 * Run 'yarn generate:css-vars' to regenerate
 */

:root {
${cssVars.join('\n')}
}
`;

  const outputPath = path.join(__dirname, '../src/css/variables.css');
  fs.writeFileSync(outputPath, cssContent, 'utf8');

  console.log(`✅ Generated CSS variables at: ${outputPath}`);
  console.log(`   ${cssVars.length} variables created`);
}

main();
